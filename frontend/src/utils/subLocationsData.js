/**
 * Direct fetch for target city sub-locations with area prioritization
 */
export function getSubLocationsForCity(locationName) {
  if (!locationName) return DEFAULT_AHMEDABAD_AREAS;

  const clean = locationName.toLowerCase();
  const primaryPart = locationName.split(',')[0].trim();

  // Find matched city in CITY_SUB_LOCATIONS
  let matchedCityKey = null;
  for (const key of Object.keys(CITY_SUB_LOCATIONS)) {
    if (clean.includes(key.toLowerCase())) {
      matchedCityKey = key;
      break;
    }
  }

  if (matchedCityKey) {
    const areas = [...CITY_SUB_LOCATIONS[matchedCityKey]];
    // If user selected a specific sub-area (e.g. "Prahlad Nagar, Ahmedabad"), prioritize it at index 0
    const areaMatchIndex = areas.findIndex(
      a => a.toLowerCase() === primaryPart.toLowerCase() ||
           a.toLowerCase().includes(primaryPart.toLowerCase()) ||
           primaryPart.toLowerCase().includes(a.toLowerCase())
    );

    if (areaMatchIndex >= 0) {
      const targetArea = areas[areaMatchIndex];
      return [targetArea, ...areas.filter((_, i) => i !== areaMatchIndex)];
    } else if (primaryPart.toLowerCase() !== matchedCityKey.toLowerCase()) {
      // It's a specific custom locality not in the list, prepend it!
      return [primaryPart, ...areas];
    }
    return areas;
  }

  // Fallback for unlisted cities or custom locations
  const generated = DEFAULT_ZONE_AREAS.map(zone => `${primaryPart} ${zone}`);
  return [primaryPart, ...generated];
}

/**
 * Direct fetch for real sub-locations & radius areas for lat/lng using geocoding service
 */
export async function fetchRadiusSubAreas(lat, lng, locationName) {
  const cityNameOnly = locationName ? locationName.split(',')[0].trim() : 'Selected Area';
  const cleanLoc = locationName ? locationName.toLowerCase() : '';

  // Return city predefined areas immediately if matched
  for (const [key, areas] of Object.entries(CITY_SUB_LOCATIONS)) {
    if (cleanLoc.includes(key.toLowerCase())) {
      return getSubLocationsForCity(locationName);
    }
  }

  const generatedSubAreas = DEFAULT_ZONE_AREAS.map(zone => `${cityNameOnly} ${zone}`);

  try {
    const foundNames = new Set();
    const radiusOffsets = [
      [0, 0],
      [0.02, 0.02],
      [-0.02, -0.02],
      [0.02, -0.02],
      [-0.02, 0.02]
    ];

    const promises = radiusOffsets.map(async ([dLat, dLng]) => {
      try {
        const queryLat = (parseFloat(lat) + dLat).toFixed(5);
        const queryLng = (parseFloat(lng) + dLng).toFixed(5);

        // Try backend reverse geocoding first
        let placeName = null;
        try {
          const res = await fetch(`/api/geocode/reverse?lat=${queryLat}&lng=${queryLng}`);
          if (res.ok) {
            const data = await res.json();
            placeName = data.suburb || data.name;
          }
        } catch (e) {}

        // Fallback to Photon reverse directly if backend is unreachable
        if (!placeName) {
          const res = await fetch(`https://photon.komoot.io/reverse?lat=${queryLat}&lon=${queryLng}`);
          if (res.ok) {
            const photonData = await res.json();
            if (photonData?.features?.[0]?.properties) {
              const p = photonData.features[0].properties;
              placeName = p.suburb || p.district || p.neighbourhood || p.name;
            }
          }
        }

        if (placeName && !placeName.toLowerCase().includes('district') && !placeName.toLowerCase().includes('taluka')) {
          foundNames.add(placeName);
        }
      } catch (e) {}
    });

    await Promise.allSettled(promises);
    const fetchedList = Array.from(foundNames);

    if (fetchedList.length > 0) {
      return Array.from(new Set([cityNameOnly, ...fetchedList, ...generatedSubAreas]));
    }
  } catch (err) {}

  return [cityNameOnly, ...generatedSubAreas];
}
